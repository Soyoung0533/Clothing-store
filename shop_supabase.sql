     OR to_regclass('public.user_profiles') IS NOT NULL THEN
    RAISE EXCEPTION '본인이 새로 만든 Supabase 프로젝트에서 실행하세요.';
  END IF;
END
$guard$;

-- 1. 회원 정보
-- Supabase Auth가 이메일/비밀번호 인증을 담당하고,
-- 이 테이블은 PRIDE의 이름·연락처·등급·포인트를 저장합니다.
CREATE TABLE IF NOT EXISTS public.shop_profiles (
  id         uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email      text,
  name       text,
  phone      text,
  grade      text NOT NULL DEFAULT 'WELCOME'
             CHECK (grade IN ('WELCOME', 'SILVER', 'GOLD', 'PRIDE')),
  points     integer NOT NULL DEFAULT 3000 CHECK (points >= 0),
  role       text NOT NULL DEFAULT 'member'
             CHECK (role IN ('member', 'admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 2. 상품 공통 정보
-- stock은 아래 옵션 테이블의 재고 합계를 보여주는 총재고 값입니다.
CREATE TABLE IF NOT EXISTS public.shop_products (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  category   text NOT NULL CHECK (category IN ('DRESSES', 'OUTERWEAR', 'BLOUSES', 'SETS')),
  price      integer NOT NULL CHECK (price >= 0),
  stock      integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image_url  text,
  description text,
  is_active  boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. 상품 옵션
-- 같은 상품의 색상·사이즈 조합마다 한 행을 만듭니다.
-- 재고는 상품 전체가 아니라 옵션 조합별로 관리합니다.
CREATE TABLE IF NOT EXISTS public.shop_product_variants (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.shop_products(id) ON DELETE CASCADE,
  sku        text NOT NULL UNIQUE,
  color      text NOT NULL,
  size       text NOT NULL CHECK (size IN ('S', 'M', 'L', 'FREE')),
  stock      integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  is_active  boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT shop_product_variants_product_color_size_key UNIQUE (product_id, color, size),
  CONSTRAINT shop_product_variants_id_product_key UNIQUE (id, product_id)
);

-- 옵션 재고가 바뀌면 상품 테이블의 총재고도 자동으로 다시 계산합니다.
CREATE OR REPLACE FUNCTION public.shop_sync_product_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  target_product_id bigint;
BEGIN
  IF TG_OP = 'DELETE' THEN
    target_product_id := OLD.product_id;
  ELSE
    target_product_id := NEW.product_id;
  END IF;

  UPDATE public.shop_products p
     SET stock = COALESCE((
       SELECT SUM(v.stock)
         FROM public.shop_product_variants v
        WHERE v.product_id = target_product_id AND v.is_active = true
     ), 0)
   WHERE p.id = target_product_id;

  IF TG_OP = 'UPDATE' AND OLD.product_id <> NEW.product_id THEN
    UPDATE public.shop_products p
       SET stock = COALESCE((
         SELECT SUM(v.stock)
           FROM public.shop_product_variants v
          WHERE v.product_id = OLD.product_id AND v.is_active = true
       ), 0)
     WHERE p.id = OLD.product_id;
  END IF;

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS shop_product_variant_stock_sync ON public.shop_product_variants;
CREATE TRIGGER shop_product_variant_stock_sync
AFTER INSERT OR UPDATE OR DELETE ON public.shop_product_variants
FOR EACH ROW EXECUTE FUNCTION public.shop_sync_product_stock();

-- 4. 주문 기본 정보
CREATE TABLE IF NOT EXISTS public.shop_orders (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  total      integer NOT NULL CHECK (total >= 0),
  status     text NOT NULL DEFAULT '주문완료'
             CHECK (status IN ('주문완료', '배송중', '배송완료', '취소')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 5. 주문 상세
-- 한 행은 한 상품의 한 옵션(예: 아이보리/S) 구매 내역입니다.
-- 주문 당시 상품명·색상·사이즈·가격을 스냅샷으로 보관합니다.
CREATE TABLE IF NOT EXISTS public.shop_order_items (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id              bigint NOT NULL REFERENCES public.shop_orders(id) ON DELETE CASCADE,
  product_id            bigint NOT NULL REFERENCES public.shop_products(id),
  variant_id            bigint NOT NULL,
  product_name_snapshot text NOT NULL,
  color_snapshot        text NOT NULL,
  size_snapshot         text NOT NULL,
  qty                   integer NOT NULL CHECK (qty > 0),
  unit_price            integer NOT NULL CHECK (unit_price >= 0),
  line_total            integer NOT NULL CHECK (line_total >= 0),
  CONSTRAINT shop_order_items_variant_product_fk
    FOREIGN KEY (variant_id, product_id)
    REFERENCES public.shop_product_variants(id, product_id)
);

CREATE INDEX IF NOT EXISTS shop_products_category_idx ON public.shop_products(category);
CREATE INDEX IF NOT EXISTS shop_variants_product_idx ON public.shop_product_variants(product_id);
CREATE INDEX IF NOT EXISTS shop_orders_user_idx ON public.shop_orders(user_id);
CREATE INDEX IF NOT EXISTS shop_order_items_order_idx ON public.shop_order_items(order_id);

-- 6. 관리자 확인 함수
CREATE OR REPLACE FUNCTION public.shop_is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM public.shop_profiles
     WHERE id = auth.uid() AND role = 'admin'
  );
$fn$;

-- 7. 회원 가입 시 프로필 자동 생성
CREATE OR REPLACE FUNCTION public.shop_handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
BEGIN
  INSERT INTO public.shop_profiles (id, email, name, phone)
  VALUES (
    NEW.id,
    NEW.email,
    NEW.raw_user_meta_data ->> 'name',
    NEW.raw_user_meta_data ->> 'phone'
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS shop_on_auth_user_created ON auth.users;
CREATE TRIGGER shop_on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.shop_handle_new_user();

-- 이미 가입한 계정이 있다면 프로필이 없는 회원만 보충 생성
